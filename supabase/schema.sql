-- Enable uuid extension if needed
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. USERS TABLE (SRS 6.1: Staff accounts for authentication)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. VISITORS TABLE (SRS 6.2: Visitor check-in/out records)
CREATE TABLE IF NOT EXISTS visitors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL CHECK (char_length(trim(full_name)) >= 2),
    phone VARCHAR(20) NOT NULL CHECK (phone ~ '^[0-9]{10}$' OR char_length(trim(phone)) = 10),
    email VARCHAR(255),
    organization VARCHAR(100),
    purpose VARCHAR(200) NOT NULL CHECK (char_length(trim(purpose)) >= 2),
    host_name VARCHAR(100) NOT NULL CHECK (char_length(trim(host_name)) >= 2),
    id_proof_type VARCHAR(50) NOT NULL CHECK (id_proof_type IN ('Aadhaar', 'Driving License', 'PAN', 'Passport', 'Other')),
    id_proof_number VARCHAR(50) NOT NULL CHECK (char_length(trim(id_proof_number)) >= 3),
    notes TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'checked_in' CHECK (status IN ('checked_in', 'checked_out')),
    check_in_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    check_out_time TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_checkout_after_checkin CHECK (check_out_time IS NULL OR check_out_time >= check_in_time)
);

-- 3. INDEXES & CONSTRAINTS FOR PERFORMANCE AND BUSINESS RULES
-- FR-2: System shall reject a new check-in if the same phone already has an open (checked_in) visit
CREATE UNIQUE INDEX IF NOT EXISTS uq_visitors_active_phone ON visitors(phone) WHERE status = 'checked_in';

-- High-performance query indexes (NFR-2, FR-7, FR-8, FR-9)
CREATE INDEX IF NOT EXISTS idx_visitors_phone ON visitors(phone);
CREATE INDEX IF NOT EXISTS idx_visitors_status ON visitors(status);
CREATE INDEX IF NOT EXISTS idx_visitors_check_in_time ON visitors(check_in_time DESC);
CREATE INDEX IF NOT EXISTS idx_visitors_host_name ON visitors(host_name);
CREATE INDEX IF NOT EXISTS idx_visitors_full_name ON visitors(full_name);
CREATE INDEX IF NOT EXISTS idx_visitors_organization ON visitors(organization);

