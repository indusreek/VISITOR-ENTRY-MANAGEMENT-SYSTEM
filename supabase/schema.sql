-- ========================================================
-- Visitor Entry Management System - Supabase PostgreSQL Schema
-- Compatible with PostgreSQL 15+ / Supabase
-- ========================================================

-- Enable uuid extension if needed
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. USERS TABLE (Staff accounts for authentication)
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. VISITORS TABLE (Visitor check-in/out records)
CREATE TABLE IF NOT EXISTS visitors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(100) NOT NULL,
    phone VARCHAR(20) NOT NULL,
    email VARCHAR(255),
    organization VARCHAR(100),
    purpose VARCHAR(200) NOT NULL,
    host_name VARCHAR(100) NOT NULL,
    id_proof_type VARCHAR(50) NOT NULL,
    id_proof_number VARCHAR(50) NOT NULL,
    notes TEXT,
    status VARCHAR(20) NOT NULL DEFAULT 'checked_in' CHECK (status IN ('checked_in', 'checked_out')),
    check_in_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    check_out_time TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. INDEXES FOR HIGH-PERFORMANCE QUERIES
CREATE INDEX IF NOT EXISTS idx_visitors_phone ON visitors(phone);
CREATE INDEX IF NOT EXISTS idx_visitors_status ON visitors(status);
CREATE INDEX IF NOT EXISTS idx_visitors_check_in_time ON visitors(check_in_time DESC);
CREATE INDEX IF NOT EXISTS idx_visitors_host_name ON visitors(host_name);
CREATE INDEX IF NOT EXISTS idx_visitors_full_name ON visitors(full_name);

-- 4. ROW LEVEL SECURITY (RLS) POLICIES
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE visitors ENABLE ROW LEVEL SECURITY;

-- Allow service role full access
CREATE POLICY "Service role full access on users" ON users
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Service role full access on visitors" ON visitors
    FOR ALL
    TO service_role
    USING (true)
    WITH CHECK (true);

-- Allow authenticated users access
CREATE POLICY "Authenticated users can read users" ON users
    FOR SELECT
    TO authenticated
    USING (true);

CREATE POLICY "Authenticated users manage visitors" ON visitors
    FOR ALL
    TO authenticated
    USING (true)
    WITH CHECK (true);

-- Allow public access if using anon key directly from client (optional fallback)
CREATE POLICY "Anon read and write visitors" ON visitors
    FOR ALL
    TO anon
    USING (true)
    WITH CHECK (true);

CREATE POLICY "Anon read users" ON users
    FOR SELECT
    TO anon
    USING (true);

